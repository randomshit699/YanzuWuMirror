"""集中管理可调参数。"""

from __future__ import annotations

from pathlib import Path

PKG_DIR = Path(__file__).resolve().parent
ASSET_DIR = PKG_DIR / "assets"
REFERENCE_DIR = ASSET_DIR / "reference"
CALIBRATION_FILE = ASSET_DIR / "calibration" / "calibration.json"

# ---------------------------------------------------------------- 摄像头
CAMERA_INDEX = 0
FRAME_WIDTH = 960
FRAME_HEIGHT = 720
# 分析分辨率：只在此宽度之上才缩小，低于它就按原分辨率分析。
# 很多usb摄像头会给 640x480，如果再缩到 480，人脸只剩 ~90px，
# 关键点精度和"脸够不够大"的判定都会受影响。
# 代价是 HOG 检测耗时（480px 约 60ms，640px 约 110ms），
# 而 128 维描述子固定 ~265ms 不随分辨率变化，所以这里放大收益大于成本。
ANALYSIS_WIDTH = 640

# ---------------------------------------------------------------- dlib 模型
DLIB_FACE_DETECTOR = "hog"  # "hog" 实时 / "cnn" 更准但慢
# 实时人脸框用的最小边长（像素），低于此值不采信，避免误检
MIN_FACE_SIZE = 55
# 判定"可以评分"的最小人脸边长。
# 注意：这只影响要不要提示用户靠近，不影响描述子精度——
# 描述子吃的是下面 FACE_ANALYSIS_SIZE 那个裁剪块，脸小会自动放大。
GOOD_FACE_SIZE = 80

# 送进关键点/描述子的人脸裁剪块目标边长（像素）。
# dlib 训练时的人脸大致在 100-200px，把裁剪块统一到这个尺寸，
# 无论人脸在画面里是 300px 还是 80px，输入尺度都一致，关键点精度才稳定。
FACE_ANALYSIS_SIZE = 224
# 裁剪时在人脸框外扩的比例，多留点上下文（发际线、下巴）
FACE_CROP_MARGIN = 0.45

FACE_TEMPLATE_SIZE = 150
# dlib 的 128 维 ResNet 描述子默认同一人阈值（欧氏距离）
DLIB_SAME_PERSON_TOLERANCE = 0.6

# ---------------------------------------------------------------- 姿态 / 画质门限
POSE_ROLL_MAX_DEG = 18.0     # 侧头角度上限
POSE_YAW_MAX = 0.30          # 鼻尖相对双眼中点的偏移（除以眼距）
MIN_FACE_BRIGHTNESS = 42.0   # 人脸区域平均亮度下限
MIN_FACE_SHARPNESS = 55.0    # 拉普拉斯方差下限

# ---------------------------------------------------------------- 打分
# 视频流里保留最近 N 帧的描述子，取中位数融合，抑制抖动
LIVE_BUFFER_SIZE = 15
# 攒够这么多样本才允许出分（太低则噪声大）
MIN_SAMPLES_TO_SCORE = 5
# 两次描述子计算之间的最小间隔（ms）。描述子约 265ms，所以这个值决定了
# 实际算力占用：设 300 基本就是持续满负荷，设 800 则留出空闲给 UI
EMBED_INTERVAL_MS = 400
# 参考图库聚合方式：取相似度最高的前 K 张的均值（top-k 融合）
REFERENCE_TOP_K = 2
# 图库自检阈值
SAME_PERSON_MIN_COS = 0.90   # 低于此值，两张参考照很可能不是同一个人
DUPLICATE_MAX_COS = 0.995    # 高于此值，两张参考照基本是同一张照片

